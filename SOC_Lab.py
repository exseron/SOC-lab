class LabRequestHandler(BaseHTTPRequestHandler):
    def do_GET(self):
        self.serve_asset(include_body=True)

    def do_HEAD(self):
        self.serve_asset(include_body=False)

    def serve_asset(self, include_body):
        path = urlsplit(self.path).path
        name = "index.html" if path == "/" else path.removeprefix("/")
        if name not in CONTENT_TYPES:
            self.send_error(404)
            return

        data = self.server.assets[name]
        self.send_response(200)
        self.send_header("Content-Type", CONTENT_TYPES[name])
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.end_headers()
        if include_body:
            self.wfile.write(data)


def main():
    parser = argparse.ArgumentParser(description="SOC / LAB yerel SIEM simülatörü")
    parser.add_argument("--port", type=int, default=8787, help="yerel port (varsayılan 8787)")
    parser.add_argument("--no-browser", action="store_true", help="tarayıcıyı otomatik açma")
    args = parser.parse_args()
    if not 0 <= args.port <= 65535:
        parser.error("--port değeri 0 ile 65535 arasında olmalı")

    try:
        server = ThreadingHTTPServer((HOST, args.port), LabRequestHandler)
    except OSError as error:
        parser.exit(1, f"Port açılamadı: {error}. Örneğin --port 8788 ile tekrar dene.\n")

    with server:
        with ZipFile(BytesIO(b64decode(EMBEDDED_ASSETS))) as archive:
            server.assets = {name: archive.read(name) for name in CONTENT_TYPES}
        url = f"http://{HOST}:{server.server_port}/"
        print(f"SOC / LAB: {url} (durdurmak için Ctrl+C)", flush=True)
        if not args.no_browser:
            webbrowser.open(url)
        try:
            server.serve_forever()
        except KeyboardInterrupt:
            print("\nSOC / LAB durduruldu.")


if __name__ == "__main__":
    main()
