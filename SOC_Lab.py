def load_assets():
    """Gömülü ZIP arşivini açar ve {dosya adı: bayt} sözlüğü döndürür."""
    with ZipFile(BytesIO(b64decode(EMBEDDED_ASSETS))) as archive:
        return {name: archive.read(name) for name in CONTENT_TYPES}


class LabRequestHandler(BaseHTTPRequestHandler):
    server_version = "SOCLab/" + __version__
    sys_version = ""

    def do_GET(self):
        self.serve_asset(include_body=True)

    def do_HEAD(self):
        self.serve_asset(include_body=False)

    def host_allowed(self):
        """DNS rebinding'e karşı yalnızca yerel Host başlıklarını kabul eder.

        Kötü niyetli bir site kendi alan adını 127.0.0.1'e çözdürse bile tarayıcı
        o alan adını Host başlığında gönderir; bu istekler reddedilir.
        """
        host = (self.headers.get("Host") or "").strip().lower()
        port = self.server.server_port
        return host in {f"127.0.0.1:{port}", f"localhost:{port}"}

    def serve_asset(self, include_body):
        if not self.host_allowed():
            self.send_error(421, "Misdirected Request")
            return

        path = urlsplit(self.path).path
        name = "index.html" if path == "/" else path.removeprefix("/")
        if name not in CONTENT_TYPES:
            self.send_error(404)
            return

        data = self.server.assets[name]
        self.send_response(200)
        self.send_header("Content-Type", CONTENT_TYPES[name])
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        if include_body:
            self.wfile.write(data)

    def end_headers(self):
        # Başarılı yanıtlar ve hata sayfaları (404, 421, 501) aynı güvenlik
        # başlıklarını taşır.
        for header, value in SECURITY_HEADERS.items():
            self.send_header(header, value)
        super().end_headers()

    def log_request(self, code="-", size="-"):
        # Her isteği yazdırmak terminali kirletir: yalnızca --verbose ile
        # veya 4xx/5xx yanıtlarda yazdır.
        try:
            failed = int(code) >= 400
        except (TypeError, ValueError):
            failed = False
        if self.server.verbose or failed:
            super().log_request(code, size)


def create_server(port=None, verbose=False):
    """Sunucuyu oluşturur. port=None ise varsayılan porttan başlayıp boş port arar."""
    candidates = [port] if port is not None else range(DEFAULT_PORT, DEFAULT_PORT + PORT_ATTEMPTS)
    assets = load_assets()
    last_error = None
    for candidate in candidates:
        try:
            server = ThreadingHTTPServer((HOST, candidate), LabRequestHandler)
        except OSError as error:
            last_error = error
            continue
        server.daemon_threads = True
        server.verbose = verbose
        server.assets = assets
        return server
    raise last_error


def main(argv=None):
    # Çıktı yönlendirildiğinde (pipe, CI) veya cp1252 konsolda Türkçe
    # karakterler UnicodeEncodeError ile çökmesin.
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(errors="replace")
    parser = argparse.ArgumentParser(description="SOC / LAB yerel SIEM simülatörü")
    parser.add_argument("--port", type=int, default=None,
                        help=f"yerel port (varsayılan {DEFAULT_PORT}; doluysa sonraki boş port denenir)")
    parser.add_argument("--no-browser", action="store_true", help="tarayıcıyı otomatik açma")
    parser.add_argument("--verbose", action="store_true", help="her HTTP isteğini terminale yazdır")
    parser.add_argument("--version", action="version", version=f"SOC / LAB {__version__}")
    args = parser.parse_args(argv)
    if args.port is not None and not 0 <= args.port <= 65535:
        parser.error("--port değeri 0 ile 65535 arasında olmalı")

    try:
        server = create_server(args.port, verbose=args.verbose)
    except OSError as error:
        parser.exit(1, f"Port açılamadı: {error}. Örneğin --port 0 (rastgele boş port) ile tekrar dene.\n")

    with server:
        url = f"http://{HOST}:{server.server_port}/"
        if args.port is None and server.server_port != DEFAULT_PORT:
            print(f"Not: {DEFAULT_PORT} portu dolu, {server.server_port} kullanılıyor.")
        print(f"SOC / LAB {__version__}: {url} (durdurmak için Ctrl+C)", flush=True)
        if not args.no_browser:
            webbrowser.open(url)
        try:
            server.serve_forever()
        except KeyboardInterrupt:
            print("\nSOC / LAB durduruldu.")


if __name__ == "__main__":
    main()
